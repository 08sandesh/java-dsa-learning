package _03_Loops;

public class _15_do_while_Loop {
    public static void main(String[] args){
        // do while loop:
        // it runs at least one time
        
        // do while loop syntax:

        // initialization;
        //  do {
        //  body/work ;
        //  increment/decrement 
        //  }(condition);

        int i = 1;
        do{
            System.out.print(i + " ");
            i++;
        }while(i <= 10 );
    }
}
