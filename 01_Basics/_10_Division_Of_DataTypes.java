public class _10_Division_Of_DataTypes {
    public static void main(String[] args){
        double a = 5/2;
        System.out.println(a);
        a = 5.0/2;
        System.out.println(a);
        a = 5/2.0;
        System.out.println(a);
        a = 5.0/2.0;
        System.out.println(a);
    }
}
