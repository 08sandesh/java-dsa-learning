public class _05_Arithmetic_Operations {
    public static void main(String[] args){
        int x = 12 , y = 10;
        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y); 

        //  Note : int (any opertor) int = int

        double a = 12 , b = 10;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b); 

        //  Note : double (any opertor) double = double
    }
}
