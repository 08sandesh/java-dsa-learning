package _05_Methods;

public class _01_Built_In_Methods {
    public static void main(String[] args){
        //  Math. wale
        System.out.println(Math.sqrt(8.6));// Square root
        System.out.println(Math.cbrt(43));// Cube root
        System.out.println(Math.abs(-99));// Mod
        System.out.println(Math.floor(-8.2));// Greatest integer function
        System.out.println(Math.ceil(-8.2));// Greatest integer function
        System.out.println(Math.min(0.3,8));// Minimum of 2 numbers
        System.out.println(Math.max(4,59));// Maximum of 2 numbers
        System.out.println(Math.max(Math.max(Math.max(1,2),3),4));// Maximum of 4 numbers
        System.out.println(Math.pow(2,5));// Power
    }
}
