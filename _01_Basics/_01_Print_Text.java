package _01_Basics;

public class _01_Print_Text {
    public static void main(String[] args) {
        // print = print the text
        System.out.print("Hello, World!");
        System.out.print("Hello, Sandesh!");
        System.out.println("");
        
        // println = print the text and move the cursor to next line
        System.out.println("Hello, World!");
        System.out.println("Hello, Sandesh!");
        
        // \n = new line
        System.out.println("Hello, World!\nHello Sandesh!");
    }
}